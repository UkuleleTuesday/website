/**
 * Mixpanel SDK vendoring script
 *
 * Bundles the "core" build of mixpanel-browser (no session-replay recorder,
 * no targeting module) into a single minified ES module at
 *   static/js/vendor/mixpanel-browser.min.js
 * which static/js/mixpanel.js imports.
 *
 * Why the SDK is served from our own origin instead of cdn.mxpnl.com:
 * that CDN is on tracking-protection blocklists, so Firefox's Enhanced
 * Tracking Protection and most ad blockers refuse the module and log three
 * errors on every page (see https://github.com/UkuleleTuesday/website/issues/125).
 * The core build is also about a tenth of the size of the CDN module, which
 * bundles the recorder.
 *
 * The generated file is committed. Re-run this script after bumping the
 * mixpanel-browser version in package.json and commit the result:
 *   pnpm run vendor:mixpanel
 */

import { build } from 'esbuild';
import { readFileSync, statSync } from 'fs';

const OUTFILE = 'static/js/vendor/mixpanel-browser.min.js';

const { version } = JSON.parse(
  readFileSync('node_modules/mixpanel-browser/package.json', 'utf8')
);

await build({
  // The published CommonJS core build; esbuild re-exports module.exports as
  // the ES module's default export.
  entryPoints: ['node_modules/mixpanel-browser/dist/mixpanel-core.cjs.js'],
  outfile: OUTFILE,
  bundle: true,
  minify: true,
  format: 'esm',
  target: ['es2017'],
  legalComments: 'none',
  banner: {
    js:
      `/*! mixpanel-browser ${version} (core build) - https://github.com/mixpanel/mixpanel-js\n` +
      ` * Licensed under the Apache License, Version 2.0.\n` +
      ` * Generated by vendor-mixpanel.mjs - do not edit by hand. */`,
  },
});

const kib = (statSync(OUTFILE).size / 1024).toFixed(1);
console.log(`Wrote ${OUTFILE} (mixpanel-browser ${version}, ${kib} KiB)`);
